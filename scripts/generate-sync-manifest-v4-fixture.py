#!/usr/bin/env python3
"""Write shared/fixtures/sync-manifest-v4.json, the golden backup manifest v4.

Standard library only. The fixture pins the canonical serialisation and the
manifestSha256 that Android (BackupManifest.kt) and iOS must both produce:
keys sorted by code point, no whitespace, UTF-8, escapes limited to \\" \\\\ \\n
\\r \\t and lowercase \\u00xx for other control characters, integers only.

Usage: python3 scripts/generate-sync-manifest-v4-fixture.py [--check]
"""

import argparse
import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "shared" / "fixtures" / "sync-manifest-v4.json"


def millis(iso: str) -> int:
    return int(datetime.strptime(iso, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc).timestamp()) * 1000


def canonical_string(value: str) -> str:
    out = ['"']
    for ch in value:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20:
            out.append("\\u%04x" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def canonical(value) -> str:
    if isinstance(value, dict):
        # Python orders str by code point, which is what the contract requires.
        return "{" + ",".join(canonical_string(k) + ":" + canonical(value[k]) for k in sorted(value)) + "}"
    if isinstance(value, list):
        return "[" + ",".join(canonical(item) for item in value) + "]"
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return canonical_string(value)
    raise TypeError("manifest values must be objects, arrays, strings, integers, booleans or null")



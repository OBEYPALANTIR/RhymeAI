def build_fixture() -> dict:
    body = sample_manifest()
    text = canonical(body)
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    manifest = dict(body)
    manifest["manifestSha256"] = digest
    return {
        "description": "Backup manifest v4 golden sample. Generated by scripts/generate-sync-manifest-v4-fixture.py; do not edit by hand.",
        "timestamps": "updatedAt, trashedAt and deletedAt are integer epoch milliseconds (the v3 encoding); savedAt and each recording's uploadedAt are ISO-8601 UTC with whole seconds and a trailing Z. A tombstone removes a song or recording only when its deletedAt is newer than the song's updatedAt or the recording's uploadedAt.",
        "escaping": "Canonical strings escape only \\\" \\\\ \\n \\r \\t and other control characters below 0x20 as lowercase \\u00xx; non-ASCII is written as UTF-8.",
        "manifest": manifest,
        "canonical": text,
        "manifestSha256": digest,
        "uploadedBytes": canonical(manifest),
    }


def render(fixture: dict) -> str:
    return json.dumps(fixture, ensure_ascii=False, indent=2) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the fixture on disk differs")
    args = parser.parse_args()
    rendered = render(build_fixture())
    if args.check:
        if FIXTURE.read_text(encoding="utf-8") != rendered:
            print(f"{FIXTURE.relative_to(ROOT)} is out of date; rerun without --check", file=sys.stderr)
            return 1
        print("sync-manifest-v4 fixture is current")
        return 0
    FIXTURE.write_text(rendered, encoding="utf-8")
    print(f"wrote {FIXTURE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

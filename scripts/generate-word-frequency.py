#!/usr/bin/env python3
"""
Generate a compact word-frequency ranked list filtered to words that appear in
the CMU pronunciation dictionary asset used by RhymeAI / Writers Block.

Output: shared/pronunciation/word-frequency.txt
  - One lowercase word per line, ordered most→least frequent.
  - Only words present in the CMU dictionary are included.
  - Capped at ~30 000 entries to keep the asset file small (~300 KB or less).

Setup (run once from the repo root or scripts/ directory):
  python3 -m venv scripts/.venv
  scripts/.venv/bin/pip install wordfreq

Run:
  scripts/.venv/bin/python3 scripts/generate-word-frequency.py
"""

import os
import sys

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(SCRIPT_DIR)

CMU_ASSET = os.path.join(REPO_ROOT, "shared", "pronunciation", "cmudict-rhymeai.tsv")
OUT_FILE = os.path.join(REPO_ROOT, "shared", "pronunciation", "word-frequency.txt")

FREQUENCY_CAP = 30_000   # max entries in the output list

# ---------------------------------------------------------------------------
# Verify wordfreq is available (it lives inside the build-time venv only).
# ---------------------------------------------------------------------------
try:
    from wordfreq import top_n_list, word_frequency  # noqa: F401
except ImportError:
    print(
        "ERROR: 'wordfreq' is not installed.\n"
        "Run from the repo root:\n"
        "  python3 -m venv scripts/.venv\n"
        "  scripts/.venv/bin/pip install wordfreq\n"
        "  scripts/.venv/bin/python3 scripts/generate-word-frequency.py",
        file=sys.stderr,
    )
    sys.exit(1)

# ---------------------------------------------------------------------------
# 1. Load the set of words in the CMU dictionary asset.
# ---------------------------------------------------------------------------
if not os.path.exists(CMU_ASSET):
    print(f"ERROR: CMU dictionary not found at {CMU_ASSET}", file=sys.stderr)
    sys.exit(1)

cmu_words: set[str] = set()
with open(CMU_ASSET, encoding="utf-8") as f:
    for line in f:
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        tab = line.find("\t")
        if tab <= 0:
            continue
        word = line[:tab].lower()
        cmu_words.add(word)

print(f"CMU dictionary: {len(cmu_words):,} distinct words loaded")

# ---------------------------------------------------------------------------
# 2. Pull the top English words from wordfreq and intersect with CMU.
#    wordfreq's top_n_list returns words in frequency order (most frequent
#    first).  We request a generous multiple of FREQUENCY_CAP to have a deep
#    enough pool after intersecting with the CMU vocabulary.
# ---------------------------------------------------------------------------
POOL_SIZE = 200_000  # pull this many from wordfreq before filtering
ranked_from_wf = top_n_list("en", POOL_SIZE)

# Filter: only keep words that (a) appear in the CMU dict and (b) contain
# only a–z (no digits, punctuation, or spaces — CMU normalized words are
# already that way, but be defensive).
filtered: list[str] = []
for w in ranked_from_wf:
    w_lower = w.lower()
    if w_lower in cmu_words and w_lower.isalpha():
        filtered.append(w_lower)
    if len(filtered) >= FREQUENCY_CAP:
        break

print(f"Filtered to {len(filtered):,} words (cap {FREQUENCY_CAP:,})")

# ---------------------------------------------------------------------------
# 3. Write output.
# ---------------------------------------------------------------------------
os.makedirs(os.path.dirname(OUT_FILE), exist_ok=True)
with open(OUT_FILE, "w", encoding="utf-8") as f:
    f.write("# RhymeAI word-frequency list\n")
    f.write("# Ordered most→least frequent (English), filtered to CMU dictionary words.\n")
    f.write(f"# Generated by scripts/generate-word-frequency.py  count={len(filtered)}\n")
    for w in filtered:
        f.write(w + "\n")

size_kb = os.path.getsize(OUT_FILE) / 1024
print(f"Wrote {len(filtered):,} words → {OUT_FILE}")
print(f"File size: {size_kb:.1f} KB")

# ---------------------------------------------------------------------------
# 4. Mirror the file to the iOS bundle resource directory (same pattern as
#    generate-pronunciation-assets.mjs does for the CMU dict).
#    New files in the synchronized project directory are auto-joined to the
#    app target — no pbxproj edit required.
# ---------------------------------------------------------------------------
IOS_OUT = os.path.join(
    REPO_ROOT,
    "Writers Block",
    "Writers Block",
    "Resources",
    "word-frequency.txt",
)
import shutil
shutil.copy2(OUT_FILE, IOS_OUT)
print(f"Copied → {IOS_OUT}")

print()
print("Top 10 words:")
for i, w in enumerate(filtered[:10], 1):
    print(f"  {i:2d}. {w}")
